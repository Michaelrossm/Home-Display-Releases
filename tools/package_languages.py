"""Build deterministic, deflated language ZIPs and the embedded catalog.

Only generated ZIP bytes enter the firmware, not these JSON source files.
Adding another complete locale and rerunning this tool extends the catalog.
"""
from pathlib import Path
import argparse
import io
import json
import re
import zipfile

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / 'resources/languages'
HEADER = ROOT / 'src/services/languages/LanguageAssets.h'
MAX_RAW, MAX_ZIP, MAX_MESSAGES = 512 * 1024, 256 * 1024, 4096

def pairs(items):
    result = {}
    for key, value in items:
        if key in result:
            raise ValueError(f'duplicate key: {key}')
        result[key] = value
    return result

def validate(data):
    if set(data) != {'schema', 'locale', 'name', 'direction', 'messages'} or type(data['schema']) is not int or data['schema'] != 1:
        raise ValueError('language schema must be 1 with known fields only')
    if not isinstance(data['locale'], str) or not re.fullmatch(r'[a-z]{2,3}(?:-[A-Z]{2})?', data['locale']):
        raise ValueError('invalid locale')
    if data['direction'] != 'ltr':
        raise ValueError('RTL layout/fonts are not implemented; do not advertise RTL')
    def text(value, size):
        return isinstance(value, str) and 0 < len(value.encode('utf-8')) <= size and not any(ord(c) < 32 and c != '\n' for c in value)
    if not text(data['name'], 64) or '\n' in data['name']:
        raise ValueError('invalid language name')
    messages = data['messages']
    if not isinstance(messages, dict) or not 1 <= len(messages) <= MAX_MESSAGES:
        raise ValueError('message count')
    for key, value in messages.items():
        if not isinstance(key, str) or not re.fullmatch(r'[a-z][a-z0-9_.]{0,95}', key) or not text(value, 2048):
            raise ValueError(f'invalid message: {key}')
    raw = json.dumps(data, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode('utf-8')
    if len(raw) > MAX_RAW:
        raise ValueError('uncompressed language limit')
    return raw

def archive(raw):
    output = io.BytesIO()
    info = zipfile.ZipInfo('locale.json', date_time=(2020, 1, 1, 0, 0, 0))
    info.compress_type = zipfile.ZIP_DEFLATED
    info.external_attr = 0o100644 << 16
    with zipfile.ZipFile(output, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=9) as package:
        package.writestr(info, raw, compresslevel=9)
    result = output.getvalue()
    if len(result) > MAX_ZIP:
        raise ValueError('compressed language limit')
    return result

def build(check=False):
    sources = sorted(SOURCES.glob('*.json'))
    data = [json.loads(path.read_text(encoding='utf-8'), object_pairs_hook=pairs) for path in sources]
    german = next((p for p in data if p['locale'] == 'de-DE'), None)
    if german is None or not 1 <= len(data) <= 16 or len({p['locale'] for p in data}) != len(data):
        raise ValueError('unique locales and German fallback required')
    lines = ['// Generated by tools/package_languages.py. Do not edit.', '#pragma once',
             '#include <cstddef>', '#include <cstdint>', 'namespace hp::languageAssets {',
             'struct Asset {const char* id;const char* name;const uint8_t* zip;size_t size;};']
    descriptors, outputs = [], {}
    for path, pack in zip(sources, data):
        if path.stem != pack['locale'] or set(pack['messages']) != set(german['messages']):
            raise ValueError(f'{path.name}: locale/translation coverage mismatch')
        for key, value in pack['messages'].items():
            if sorted(re.findall(r'\{[A-Za-z0-9_]+\}', value)) != sorted(re.findall(r'\{[A-Za-z0-9_]+\}', german['messages'][key])):
                raise ValueError(f'{path.name}: placeholder mismatch: {key}')
        raw = validate(pack)
        blob = archive(raw)
        symbol = pack['locale'].replace('-', '_')
        lines.append(f'inline constexpr uint8_t {symbol}[]={{')
        lines.extend('    ' + ','.join(f'0x{b:02x}' for b in blob[i:i+20]) + ',' for i in range(0, len(blob), 20))
        lines.append('};')
        descriptors.append('{'+json.dumps(pack['locale'])+','+json.dumps(pack['name'], ensure_ascii=False)+','+symbol+',sizeof('+symbol+')}')
        outputs[path.with_suffix('.zip')] = blob
    lines.extend(['inline constexpr Asset catalog[]={'+','.join(descriptors)+'};', '}'])
    outputs[HEADER] = ('\n'.join(lines)+'\n').encode('utf-8')
    for path, content in outputs.items():
        if check:
            actual = path.read_bytes() if path.exists() else None
            if actual is not None and path == HEADER:
                actual = actual.replace(b'\r\n', b'\n')
            if actual != content:
                raise ValueError(f'generated language asset outdated: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    return data

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for pack in build(args.check):
        print(f"{pack['locale']}: ZIP ready ({len(pack['messages'])} messages)")
